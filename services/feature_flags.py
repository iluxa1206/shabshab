"""Тумблеры слоёв приложения — переменными окружения, без релиза.

Слой фиксов (витрина, прогрев метрик, пул котировок и стаканов, тики в ленте)
живёт рядом с флоатерами и делит с ними один счётный такт и один event loop.
Когда он мешает — его надо гасить целиком и мгновенно, а не выкатывать правку:
FIXED_TAB=0 в .env прода и рестарт контейнера.

FIXED_STREAM гасит только ЖИВОЙ слой (пул Alor + тики), оставляя витрину на
десятиминутном прогреве, — это средняя ступень между «всё как обычно» и
«фиксов нет вовсе».
"""
import os


def _on(name: str, default: str = "1") -> bool:
    return os.getenv(name, default).strip().lower() not in ("0", "false", "no", "off")


def fixed_enabled() -> bool:
    """Слой фиксов вообще существует: витрина, прогрев метрик, стрим, тики."""
    return _on("FIXED_TAB")


def fixed_stream_enabled() -> bool:
    """Фиксы в живом слое: пул котировок/стаканов Alor и тики в ленте.
    Выключается отдельно — витрина при этом остаётся на прогреве."""
    return fixed_enabled() and _on("FIXED_STREAM")
