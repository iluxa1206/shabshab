/**
 * ГОРИЗОНТ ПРАЙСИНГА строки — та дата, к которой посчитаны её метрики.
 *
 * У бумаги с офертой их две: погашение и оферта. Какую считать «сроком»,
 * решает не справочник, а ПРАВИЛО ЦЕНЫ (бэк, services/valuation): цена ниже
 * цены пут-выкупа — рынок прайсит к оферте, выше цены call-выкупа — к коллу,
 * иначе к погашению. Готовый ответ приезжает в строке полем preferred_horizon,
 * и в таблице он же подсвечен синим у нужной даты (.mat-yrs.mat-hz).
 *
 * Всё, что называет себя «сроком» — окно фильтра, сортировка колонки, ось
 * графика, — обязано мерить ЭТУ дату. Иначе интерфейс спорит сам с собой: в
 * строке синим стоит «2,7 г», а список отсортирован так, будто бумага
 * одиннадцатилетняя.
 *
 * У ФИКСОВ выбора нет вовсе: их поток обрывается на оферте (дальше купоны
 * неизвестны), поэтому метрики всегда считаются к put_date, если она есть, —
 * правила цены там нет. Функция одна на обе витрины: поля разные
 * (offer_date + preferred_horizon у флоатеров, put_date у фиксов), а вопрос
 * тот же.
 */

/** Дата горизонта. null — у строки нет ни оферты, ни погашения (перп либо
 *  дыра в справочнике): такие прячутся из окна срока и уезжают в конец
 *  сортировки, а не притворяются бессрочно короткими. */
export function horizonDate(b) {
  if (!b) return null;
  // ФЛОАТЕР: горизонт выбран правилом цены на бэке, оферта берётся только когда
  // выбрана она. Строка фикса приходит БЕЗ preferred_horizon — там put_date и
  // есть горизонт. Порядок именно такой: появись у флоатера поле put_date,
  // безусловная проверка перебила бы правило цены и вернула оферту бумаге,
  // которую рынок прайсит к погашению.
  if (b.preferred_horizon) {
    const toOffer = b.preferred_horizon === "put" || b.preferred_horizon === "call";
    return (toOffer && b.offer_date) || b.maturity_date || null;
  }
  return b.put_date || b.maturity_date || null;   // фикс: поток рвётся на оферте
}

/** Лет до горизонта, ACT/365.25. null — горизонта нет (перп/дыра). Считается
 *  на КАЖДОМ чтении: срок тает каждый день, а строка живёт в кэше дольше. */
export function horizonYears(b, today = new Date()) {
  const d = horizonDate(b);
  if (!d) return null;
  const t = Date.parse(String(d).slice(0, 10));
  if (Number.isNaN(t)) return null;
  return (t - today.getTime()) / (365.25 * 24 * 3600 * 1000);
}
