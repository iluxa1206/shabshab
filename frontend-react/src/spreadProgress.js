/**
 * ПРОГРЕСС ЗАПОЛНЕНИЯ СПРЕДОВ по строкам таблицы.
 *
 * Спред стороны считает движок на бэке (по методике, пачками: сетка цен,
 * очередь сторон, догрев контекстов), поэтому в колонках BID/OFFER прочерк
 * живёт от секунд до минут после загрузки страницы или смены фильтра. Без
 * индикатора «ещё считается» неотличимо от «числа не будет» — ровно на это
 * жаловались пользователи.
 *
 * Считаем по ЦЕНЕ стороны, а не по числу строк: если цены нет (стороны в
 * стакане нет, а при фильтре по объёму — книги не хватило на тикет), прочерк
 * в спреде окончательный и ждать там нечего. Иначе полоса никогда не доходила
 * бы до конца.
 *
 * Работает одинаково в обоих режимах: при фильтре по объёму applyVolume уже
 * подменил цену и спред стороны на числа набора (см. vwap.js), а поля те же.
 */

/** Одна сторона: {done, total}. */
export function sideProgress(rows, pxField, spreadField) {
  let done = 0, total = 0;
  for (const b of rows || []) {
    if (b[pxField] == null) continue;
    total += 1;
    if (b[spreadField] != null) done += 1;
  }
  return { done, total };
}

/** Несколько сторон одной суммой — для общей полосы за шапкой приложения.
 *  sides: [[pxField, spreadField], …]. Считаем СЛОТАМИ «строка × сторона»:
 *  когда ждём обе стороны, половина посчитанного — это честная половина. */
export function spreadProgress(rows, sides) {
  let done = 0, total = 0;
  for (const [px, spread] of sides) {
    const p = sideProgress(rows, px, spread);
    done += p.done; total += p.total;
  }
  return { done, total };
}
