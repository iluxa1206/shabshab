// Склейка сохранённой раскладки колонок с текущим набором версии.
//
// Одно правило на все таблицы (монитор, фиксы, лента, история размещений):
// раньше у каждой было своё — новые колонки то дописывались в хвост за
// кнопками строки, то терялись вовсе (история размещений), и новую колонку
// видел только тот, кто ни разу не трогал раскладку.
//
// saved    — что лежит в localStorage (может быть чем угодно: null, мусор,
//            ключи снесённых колонок);
// defaults — порядок и набор по умолчанию у ЭТОЙ версии;
// valid    — все допустимые ключи, если таблица умеет скрывать/показывать
//            колонки сверх набора по умолчанию (иначе = defaults);
// known    — набор по умолчанию, каким его видел пользователь в прошлый раз:
//            колонка из defaults, которой нет ни в saved, ни в known, — НОВАЯ
//            (показываем), а которой нет в saved, но есть в known, — скрыта
//            самим пользователем (не трогаем). Без known все недостающие
//            считаются новыми;
// tail     — ключ, обязанный стоять последним (кнопки строки в ленте):
//            сохранённая раскладка могла быть записана старым правилом
//            «новое — в конец» уже ПОСЛЕ него.
//
// Новая колонка встаёт следом за ближайшим присутствующим соседом слева из
// порядка по умолчанию — там, где её ждут, а не в хвосте.
export function mergeColumnLayout(saved, defaults, { valid, known, tail } = {}) {
  const ok = new Set(valid || defaults);
  const kept = Array.isArray(saved) ? saved.filter((k) => ok.has(k)) : [];
  if (!kept.length) return defaults;
  const seen = known ? new Set(known) : null;
  const out = [...kept];
  defaults.forEach((k, i) => {
    if (out.includes(k) || (seen && seen.has(k))) return;
    let at = -1;
    for (let j = i - 1; j >= 0 && at < 0; j--) at = out.indexOf(defaults[j]);
    out.splice(at + 1, 0, k);
  });
  if (tail && out.includes(tail)) {
    out.splice(out.indexOf(tail), 1);
    out.push(tail);
  }
  return out;
}
